def text_of(el):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', ' ', el or ''))).strip()


def fetch_feed(url, limit=5):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (website feed reader; +https://github.com)'})
    data = urllib.request.urlopen(req, timeout=25).read()
    tree = ET.fromstring(data)
    ns = {'a': 'http://www.w3.org/2005/Atom'}
    items = []
    if tree.tag.endswith('feed'):   # Atom (GitHub and others)
        for e in tree.findall('a:entry', ns)[:limit]:
            link = e.find('a:link', ns)
            when = (e.findtext('a:published', '', ns) or e.findtext('a:updated', '', ns))[:10]
            items.append({'title': text_of(e.findtext('a:title', '', ns)), 'link': link.get('href') if link is not None else '', 'date': when})
    else:                           # RSS 2.0
        for it in tree.iter('item'):
            if len(items) >= limit: break
            when = ''
            if it.findtext('pubDate'):
                try: when = email.utils.parsedate_to_datetime(it.findtext('pubDate')).date().isoformat()
                except (TypeError, ValueError): when = ''
            title = text_of(it.findtext('title')) or text_of(it.findtext('description'))
            items.append({'title': title[:140] + ('…' if len(title) > 140 else ''), 'link': it.findtext('link') or '', 'date': when})
    return [i for i in items if i['title'] and re.match(r'^https?://', i['link'] or '')]


def build_socials(root, site, pages, do_fetch):
    data = json.load(open(os.path.join(root, '_data', 'socials.json'), encoding='utf-8'))
    cache_path = os.path.join(root, '_data', 'social-cache.json')
    cache = json.load(open(cache_path, encoding='utf-8')) if os.path.exists(cache_path) else {}
    pg = pages['socials']
    cards = []
    for acc in data['accounts']:
        if not acc.get('enabled', True) or not acc.get('url'):
            continue
        feed, items = acc.get('feed', ''), []
        if feed:
            if do_fetch:
                try:
                    items = fetch_feed(feed); cache[feed] = {'items': items, 'fetched': dt.date.today().isoformat()}
                except Exception as ex:  # keep the last good copy if a feed is down
                    print(f'! could not read the {acc["name"]} feed ({ex.__class__.__name__}); using the last saved copy')
            items = items or cache.get(feed, {}).get('items', [])
        icon = site['icons'].get(acc.get('icon', acc['name'].lower()), '')
        lst = ''
        if items:
            lis = ''.join(f'<li><a href="{E(i["link"])}" target="_blank" rel="noopener">{E(i["title"])}</a>'
                          + (f'<time datetime="{E(i["date"])}">{E(human(dt.date.fromisoformat(i["date"])))}</time>' if re.match(r'\d{4}-\d{2}-\d{2}$', i.get('date', '')) else '') + '</li>' for i in items)
            lst = f'<h3 class="social-card__sub">Latest</h3><ul class="feed-list">{lis}</ul>'
        elif feed:
            lst = f'<p class="social-card__note">{E(pg["pending_text"])}</p>'
        else:
            lst = f'<p class="social-card__note">{E(pg["no_feed_text"])}</p>'
        rss = f'<a class="social-card__rss" href="{E(feed)}">Feed</a>' if feed else ''
        cards.append(f'''<article class="social-card">
  <div class="social-card__head">{icon}<div><h2>{E(acc['name'])}</h2><p class="mono">{E(acc.get('handle', ''))}</p></div></div>
  {f'<p>{E(acc["about"])}</p>' if acc.get('about') else ''}
  {lst}
  <p class="social-card__actions"><a class="btn btn--sm" href="{E(acc['url'])}" target="_blank" rel="noopener me"><span class="roll"><span>Follow on {E(acc['name'])}</span><span aria-hidden="true">Follow on {E(acc['name'])}</span></span></a>{rss}</p>
</article>''')
    json.dump(cache, open(cache_path, 'w', encoding='utf-8'), indent=1)
    body = f'''<section class="page-hero"><div class="wrap">
  {crumbs([('Home', './'), ('Socials', '')])}
  <p class="eyebrow">Socials</p>
  <h1>{E(pg['heading'])}</h1>
  <p class="lead">{E(pg['intro'])}</p>
</div></section>
<section class="section" style="padding-top:0"><div class="wrap">
  <div class="social-grid">{''.join(cards)}</div>
  <div class="subscribe">
    <div><p class="eyebrow">Subscribe</p><h2 class="h3">{E(pg['subscribe_heading'])}</h2><p>{E(pg['subscribe_text'])}</p></div>
    <p class="subscribe__actions"><a class="btn btn--ghost btn--sm" href="feed.xml"><span class="roll"><span>RSS feed</span><span aria-hidden="true">RSS feed</span></span></a><button class="copy-btn" type="button" data-copy="{E(site['url'])}/feed.xml">Copy feed address</button></p>
  </div>
  <p class="social-updated">{E(pg['updated_text'])} {E(human(dt.date.today()))}.</p>
</div></section>'''
    jsonld = ld(crumbs_ld(site['url'], [('Home', ''), ('Socials', 'socials.html')]))
    tpl = open(os.path.join(root, '_templates', 'socials.html'), encoding='utf-8').read()
    page = fill(tpl, title=E(pg['title']), description=E(pg['description']), canonical=E(site['url'] + '/socials.html'), og_image=E(site['og_default']), jsonld=jsonld, body=body)
    open(os.path.join(root, 'socials.html'), 'w', encoding='utf-8').write(page)
    print(f'socials: {len(cards)} accounts')



