def load_data(root, name):
    p = os.path.join(root, '_data', name)
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else None


def local(src, what):
    """Files must live on this site: the security policy blocks images and video from other addresses."""
    src = (src or '').strip()
    if re.match(r'[a-z]+:', src, re.I) or src.startswith('//'):
        WARN.append(f'{what}: "{src}" is on another site. Upload the file to assets/media and use its path instead.')
        return ''
    return src.lstrip('/')


def ratio_wh(ratio, w=1600):
    try:
        a, b = (float(x) for x in ratio.split('/'))
        return w, round(w * b / a)
    except ValueError:
        return w, round(w * 3 / 4)


def placeholder(kind, label, spec, ratio):
    icon, word = (PLAY, 'Video') if kind == 'video' else (CAMERA, 'Photo')
    return (f'<div class="ph ph--{kind}" style="--ar:{E(ratio)}">{icon}<b>{word} placeholder</b>'
            f'<span>{E(label)}</span><small>{E(spec)}</small></div>')


def render_media(slot_id, media, allow_placeholder=True):
    m = (media or {}).get('slots', {}).get(slot_id)
    if m is None:
        WARN.append(f'media.json has no spot called "{slot_id}".')
        return ''
    ratio = m.get('ratio', '4/3')
    src = local(m.get('src'), slot_id)
    cap = f'<figcaption>{E(m["caption"])}</figcaption>' if m.get('caption') else ''
    if src:
        w, h = ratio_wh(ratio)
        if m.get('type') == 'video':
            poster = local(m.get('poster'), slot_id + ' poster')
            vtt = local(m.get('captions'), slot_id + ' captions')
            return (f'<figure class="media" style="--ar:{E(ratio)}"><video controls playsinline preload="none" width="{w}" height="{h}"'
                    + (f' data-poster="{E(poster)}"' if poster else '') + f' aria-label="{E(m.get("alt") or m.get("label", ""))}">'
                    f'<source src="{E(src)}" type="video/mp4">'
                    + (f'<track kind="captions" src="{E(vtt)}" srclang="en" label="English" default>' if vtt else '')
                    + f'</video>{cap}</figure>')
        if not m.get('alt'):
            WARN.append(f'{slot_id}: add a short description in "alt".')
        return (f'<figure class="media" style="--ar:{E(ratio)}"><img src="{E(src)}" width="{w}" height="{h}" alt="{E(m.get("alt", ""))}" '
                f'loading="lazy" decoding="async">{cap}</figure>')
    if not media.get('show_placeholders', True) or not allow_placeholder:
        return ''
    WARN.append(f'Placeholder still showing: {slot_id} ({m.get("used_on", "")}).')
    return placeholder(m.get('type', 'photo'), m.get('label', ''), m.get('spec', ''), ratio)


def render_testimonials(data, attrs):
    if not data:
        return ''
    show_ph = data.get('show_placeholders', True)
    cards = []
    for i, t in enumerate(data.get('items', [])):
        if (t.get('quote') or '').strip() and t.get('sample') and not show_ph:
            continue   # sample text is never shown once placeholders are switched off
        if (t.get('quote') or '').strip():
            if t.get('sample'):
                WARN.append(f'Sample testimonial still showing: testimonial {i + 1}. Replace it with a real quote (and delete "sample") before launch.')
            photo = local(t.get('photo'), f'testimonial {i + 1} photo')
            pic = f'<img src="{E(photo)}" width="112" height="112" alt="" loading="lazy" decoding="async">' if photo else PERSON_ICON
            res = f'<p class="tcard__result">{E(t["result"])}</p>' if t.get('result') else ''
            tag = '<span class="ph-tag">Sample · replace</span>' if t.get('sample') else ''
            cards.append(f'<figure class="tcard{" is-sample" if t.get("sample") else ""}">{tag}<blockquote><p>{E(t["quote"].strip())}</p></blockquote>{res}'
                         f'<figcaption><span class="tcard__photo">{pic}</span><span><b>{E(t.get("name", ""))}</b><span>{E(t.get("role", ""))}</span></span></figcaption></figure>')
        elif show_ph:
            WARN.append(f'Placeholder still showing: testimonial {i + 1} ({t.get("who_to_ask", "")}).')
            cards.append(f'<figure class="tcard is-ph"><span class="ph-tag">Placeholder</span><blockquote><p>{E(t.get("ask_for", "A quote from someone you have worked with."))}</p></blockquote>'
                         f'<figcaption><span class="tcard__photo">{PERSON_ICON}</span><span><b>Their name</b><span>{E(t.get("who_to_ask", "Their title and company"))}</span></span></figcaption></figure>')
    if not cards:
        return ''
    tone = ' sage' if attrs.get('tone') == 'sage' else ''
    return (f'<section class="section{tone}" aria-labelledby="t-h"><div class="wrap">'
            f'<div class="section-head"><div><p class="eyebrow">{E(data.get("eyebrow", "In their words"))}</p><h2 class="h2" id="t-h">{E(data.get("heading", "What people say"))}</h2></div></div>'
            f'<div class="tgrid">{"".join(cards)}</div></div></section>')


def render_brands(data):
    if not data or not data.get('items'):
        return ''
    show_ph = data.get('show_placeholders', True)
    tiles = []
    for b in data['items']:
        logo = local(b.get('logo'), b.get('name', 'logo'))
        inner = (f'<img src="{E(logo)}" width="200" height="80" alt="{E(b["name"])}" loading="lazy" decoding="async">' if logo
                 else (f'<span class="ph-mini" aria-hidden="true">Logo</span>' if show_ph else '') + f'<span>{E(b["name"])}</span>')
        cls = 'brand' + ('' if logo or not show_ph else ' is-ph')
        href = f'case-studies/{E(b["case"])}.html' if b.get('case') else ''
        tiles.append(f'<li><a class="{cls}" href="{href}">{inner}</a></li>' if href else f'<li><span class="{cls}">{inner}</span></li>')
    return (f'<section class="brands" aria-labelledby="brands-h"><div class="wrap"><p class="eyebrow" id="brands-h">{E(data.get("eyebrow", "Brands"))}</p>'
            f'<ul class="brand-grid">{"".join(tiles)}</ul></div></section>')


def render_latest(posts):
    live = posts[:3]   # drafts are only in the list when the tool runs with --drafts
    if not live:
        return ''
    cards = []
    for p in live:
        meta = [f'<time datetime="{p["date"].isoformat()}">{human(p["date"])}</time>']
        if p['link']:
            host = urlparse(p['link']).netloc.replace('www.', '')
            meta.append(f'On {E(host)}')
            title = f'<a href="{E(p["link"])}" target="_blank" rel="noopener">{E(p["title"])}<span class="sr-only"> (opens on {E(host)})</span><span aria-hidden="true"> ↗</span></a>'
        else:
            meta.append(f'{p["minutes"]} min read')
            title = f'<a href="articles/{p["slug"]}.html">{E(p["title"])}</a>'
        cards.append(f'<article class="post-card"><p class="post-card__meta">{" · ".join(meta)}</p><h3 class="post-card__title">{title}</h3>'
                     + (f'<p>{E(p["description"])}</p>' if p['description'] else '') + '</article>')
    return (f'<section class="section" aria-labelledby="la-h"><div class="wrap"><div class="section-head"><div><p class="eyebrow">Latest articles</p>'
            f'<h2 class="h2" id="la-h">Notes on measurable growth</h2></div><a class="text-link" href="articles.html">All articles</a></div>'
            f'<div class="post-list">{"".join(cards)}</div></div></section>')



def render_engagements(data):
    if not data or not data.get('items'):
        return ''
    show_ph = data.get('show_placeholders', True)
    cards = []
    for i, p in enumerate(data['items']):
        price = (p.get('price') or '').strip()
        if price:
            pr = E(price)
        elif show_ph:
            WARN.append(f'Placeholder still showing: price for "{p.get("name", i + 1)}" (engagements.json).')
            pr = '<span class="ph-tag">Placeholder</span> Set your price'
        else:
            pr = E(data.get('price_on_request', 'Scoped to your goal'))
        inc = ''.join(f'<li>{E(t)}</li>' for t in p.get('includes', []))
        meta = ''.join(f'<div><dt>{a}</dt><dd>{b}</dd></div>' for a, b in
                       [('For', E(p.get('for', ''))), ('Timeline', E(p.get('timeline', ''))), ('Investment', pr)] if b)
        cards.append(f'<article class="card pkg"><p class="cap-card__n">0{i + 1}</p><h3>{E(p.get("name", ""))}</h3>'
                     f'<p class="pkg__outcome">{E(p.get("outcome", ""))}</p><ul class="checks">{inc}</ul><dl class="pkg__meta">{meta}</dl></article>')
    return f'<div class="cards-3 pkgs">{"".join(cards)}</div>'

def build_blocks(root, posts):
    media, tst, brands = load_data(root, 'media.json'), load_data(root, 'testimonials.json'), load_data(root, 'brands.json')
    eng = load_data(root, 'engagements.json')
    changed = 0
    for name in sorted(os.listdir(root)):
        if not name.endswith('.html'):
            continue
        path = os.path.join(root, name)
        s = open(path, encoding='utf-8').read()
        if '<!-- wc:' not in s:
            continue
        def rep(m):
            kind, attrs = m.group(2), dict(re.findall(r'([a-z]+)=([^ >]+)', m.group(3)))
            if kind == 'media':
                inner = render_media(attrs.get('id', ''), media, attrs.get('placeholder') != 'no')
            elif kind == 'testimonials':
                inner = render_testimonials(tst, attrs)
            elif kind == 'brands':
                inner = render_brands(brands)
            elif kind == 'latest-articles':
                inner = render_latest(posts)
            elif kind == 'engagements':
                inner = render_engagements(eng)
            else:
                return m.group(0)
            return m.group(1) + inner + m.group(5)
        new = BLOCK.sub(rep, s)
        if new != s:
            open(path, 'w', encoding='utf-8').write(new)
            changed += 1
    seen = list(dict.fromkeys(WARN))
    print(f'blocks: {changed} pages updated' + (f', {len(seen)} notes:' if seen else ''))
    for w in seen:
        print('  - ' + w)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--root', default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument('--drafts', action='store_true')
    ap.add_argument('--no-fetch', action='store_true')
    a = ap.parse_args()
    site = json.load(open(os.path.join(a.root, '_data', 'site.json'), encoding='utf-8'))
    pages = json.load(open(os.path.join(a.root, '_data', 'pages.json'), encoding='utf-8'))
    posts = load_articles(a.root, a.drafts)
    build_articles(a.root, posts, site, pages)
    build_socials(a.root, site, pages, not a.no_fetch)
    build_blocks(a.root, posts)


if __name__ == '__main__':
    main()
