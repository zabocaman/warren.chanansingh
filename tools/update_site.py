#!/usr/bin/env python3
"""Rebuilds the Articles and Socials parts of the website.

Run it from the website's folder (GitHub Actions does this for you on every push and once a day):

    python3 tools/update_site.py

What it reads
  _articles/*.md        one file per article, or per link to something you wrote elsewhere
  _data/pages.json      headings and intros for the Articles and Socials pages
  _data/socials.json    your social accounts, and the feed address for each one (if it has one)
  _data/site.json       site address, author and icons (written when the site was built; rarely changes)
  _data/testimonials.json   quotes for the home and Hire me pages
  _data/brands.json         the brand strip on the home page (names now, logos once you have permission)
  _data/media.json          every photo and video spot on the site
  _data/engagements.json    the engagement packages on the Work with me page
  _templates/*.html     the page shells: header, footer and styles already in place

What it writes
  articles.html, articles/<slug>.html, feed.xml, socials.html, and the Articles lines in sitemap.xml and llms.txt
  The testimonials, brand strip, photos, videos and latest articles inside the site's pages (between <!-- wc:... --> markers)

Options
  --root DIR     the website folder (default: the folder above this script)
  --drafts       also publish articles marked "draft: true" (for previewing on your computer)
  --no-fetch     do not download social feeds; use the last saved copy
"""
