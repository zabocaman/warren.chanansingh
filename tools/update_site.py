# ---------------------------------------------------------------- reading articles
def parse_front_matter(text):
    meta, body = {}, text
    if text.startswith('---'):
        end = text.find('\n---', 3)
        if end != -1:
            for line in text[3:end].strip().splitlines():
                if ':' in line and not line.lstrip().startswith('#'):
                    k, v = line.split(':', 1)
                    meta[k.strip().lower()] = v.strip().strip('"').strip("'")
            body = text[end + 4:].lstrip('\n')
    return meta, body


def to_html(md):
    try:
        import markdown  # pip install markdown
        return markdown.markdown(md, extensions=['extra', 'sane_lists', 'smarty'], output_format='html')
    except ImportError:
        return mini_markdown(md)


def mini_markdown(md):
    """A small Markdown converter, used only if the 'markdown' package is not installed."""
    def inline(s):
        s = E(s)
        s = re.sub(r'!\[([^\]]*)\]\(([^)\s]+)\)', r'<img src="\2" alt="\1" loading="lazy">', s)
        s = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', r'<a href="\2">\1</a>', s)
        s = re.sub(r'`([^`]+)`', r'<code>\1</code>', s)
        s = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', s)
        s = re.sub(r'(?<![*\w])\*([^*]+)\*(?!\w)', r'<em>\1</em>', s)
        return s
    out, para, lst, ltype, quote = [], [], [], None, []
    def flush():
        nonlocal para, lst, ltype, quote
        if para: out.append('<p>' + inline(' '.join(para)) + '</p>'); para = []
        if lst: out.append(f'<{ltype}>' + ''.join(f'<li>{inline(i)}</li>' for i in lst) + f'</{ltype}>'); lst = []; ltype = None
        if quote: out.append('<blockquote><p>' + inline(' '.join(quote)) + '</p></blockquote>'); quote = []
    for raw in md.splitlines():
        line = raw.rstrip()
        if not line.strip(): flush(); continue
        m = re.match(r'^(#{2,4})\s+(.*)', line)
        if m: flush(); n = len(m.group(1)); out.append(f'<h{n}>{inline(m.group(2))}</h{n}>'); continue
        m = re.match(r'^\s*[-*]\s+(.*)', line)
        if m:
            if para or quote: flush()
            ltype = ltype or 'ul'; lst.append(m.group(1)); continue
        m = re.match(r'^\s*\d+[.)]\s+(.*)', line)
        if m:
            if para or quote: flush()
            ltype = ltype or 'ol'; lst.append(m.group(1)); continue
        if line.startswith('>'): quote.append(line.lstrip('> ')); continue
        para.append(line.strip())
    flush()
    return '\n'.join(out)


def slugify(s):
    s = re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')
    return s[:80] or 'article'


def load_articles(root, drafts):
    folder = os.path.join(root, '_articles')
    posts = []
    if not os.path.isdir(folder):
        return posts
    for name in sorted(os.listdir(folder)):
        if not name.endswith('.md') or name.startswith(('_', '.')) or name.lower() == 'readme.md':
            continue
        meta, body = parse_front_matter(open(os.path.join(folder, name), encoding='utf-8').read())
        if meta.get('draft', '').lower() in ('true', 'yes', '1') and not drafts:
            continue
        m = re.match(r'(\d{4}-\d{2}-\d{2})-(.+)\.md$', name)
        date_s = meta.get('date') or (m.group(1) if m else '')
        try:
            date = dt.date.fromisoformat(date_s[:10])
        except ValueError:
            print(f'! {name}: needs a date like 2026-10-20 (in the file name or a "date:" line); skipped')
            continue
        title = meta.get('title') or (m.group(2).replace('-', ' ').capitalize() if m else name[:-3])
        link = meta.get('link', '')
        if link and not re.match(r'^https?://', link):
            print(f'! {name}: "link" must start with https://; skipped'); continue
        words = len(re.findall(r'\w+', body))
        tags = [t.strip() for t in re.split(r'[,\[\]]', meta.get('tags', '')) if t.strip()]
        updated_s = meta.get('updated', '')
        try:
            updated = dt.date.fromisoformat(updated_s[:10]) if updated_s else date
        except ValueError:
            updated = date
        posts.append({
            'file': name, 'title': title, 'date': date, 'updated': updated, 'link': link,
            'slug': slugify(meta.get('slug') or (m.group(2) if m else name[:-3])),
            'description': meta.get('description', ''), 'tags': tags,
            'image': meta.get('image', ''), 'image_alt': meta.get('image_alt', ''),
            'canonical': meta.get('canonical', ''), 'html': '' if link else to_html(body),
            'minutes': max(1, round(words / 230)), 'draft': meta.get('draft', '').lower() in ('true', 'yes', '1'),
        })
    posts.sort(key=lambda p: (p['date'], p['title']), reverse=True)
    return posts


def human(d):
    return f'{d:%B} {d.day}, {d.year}'


def fill(tpl, **kw):
    for k, v in kw.items():
        tpl = tpl.replace('{{' + k + '}}', v)
    return tpl


def ld(obj):
    return '<script type="application/ld+json">' + json.dumps(obj, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/') + '</script>'


def crumbs(items):
    lis = ''.join(f'<li><a href="{E(h)}">{E(t)}</a></li>' if h else f'<li aria-current="page">{E(t)}</li>' for t, h in items)
    return f'<ol class="crumbs" aria-label="Breadcrumb">{lis}</ol>'


def crumbs_ld(site, items):
    return {'@context': 'https://schema.org', '@type': 'BreadcrumbList',
            'itemListElement': [{'@type': 'ListItem', 'position': i + 1, 'name': n, 'item': site + '/' + u} for i, (n, u) in enumerate(items)]}


